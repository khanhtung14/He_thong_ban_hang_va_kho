export function formatCurrencyVND(val) {
  if (!val || isNaN(val)) return '0 đ';
  if (val >= 1000000000) {
    return (val / 1000000000).toFixed(2).replace('.', ',') + ' tỷ đ';
  }
  return (val / 1000000).toLocaleString('vi-VN') + ' triệu đ';
}

